CREATE TABLE Sports_Stud (
    ROLL NUMBER PRIMARY KEY,
    NAME VARCHAR2(30) UNIQUE,
    DEPT VARCHAR2(10) CHECK (DEPT IN ('IT','CS')),
    SPORTS_FEE NUMBER CHECK (SPORTS_FEE >= 1000)
);
CREATE TABLE Cultural_Stud (
    ROLL NUMBER PRIMARY KEY,
    NAME VARCHAR2(30) UNIQUE,
    DEPT VARCHAR2(10) CHECK (DEPT IN ('IT','CS')),
    CUL_FEES NUMBER CHECK (CUL_FEES >= 600)
);
